import {readFileSync,writeFileSync} from 'node:fs';
import {startChrome,CDP,openPage} from './cdp.mjs';
const base=`http://127.0.0.1:${readFileSync('/tmp/pex/PORT','utf8').trim()}`;
const {version}=JSON.parse(readFileSync('/tmp/pex/ui-candidate.json','utf8'));
const chrome=await startChrome(),cdp=new CDP();await cdp.connect(chrome.wsUrl);
const p=await openPage(cdp,chrome.port);let fail=0;
const ck=(n,ok)=>{console.log(`${ok?'PASS':'FAIL'} ${n}`);if(!ok)fail++;};
await p.goto(base+'/model-center#tab=history');await p.settle(1800);
await p.eval(`window.__receipts=[];window.confirm=()=>true;window.alert=m=>window.__receipts.push(m)`);
async function click(sel){const pos=await p.eval(`(()=>{const b=document.querySelector(${JSON.stringify(sel)});if(!b)return null;b.scrollIntoView({block:'center'});const r=b.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2};})()`);if(!pos)return false;for(const type of ['mousePressed','mouseReleased'])await cdp.send('Input.dispatchMouseEvent',{type,...pos,button:'left',clickCount:1},p.sessionId);await p.settle(1800);return true;}
ck('历史页签候选的审批按钮可真实点击',await click('#mcHistory .btn:not(.ghost)'));
let summary=await(await fetch(base+'/api/model-center')).json();
ck('UI 审批发布后接口线上版本更新',summary.summary.active_version===version);
ck('审批回执可见且留在历史页签',await p.eval(`window.__receipts.some(t=>/发布/.test(t))&&location.hash==='#tab=history'`));
ck('历史页签基础模型回滚按钮可真实点击',await click('#mcHistory .btn.ghost'));
summary=await(await fetch(base+'/api/model-center')).json();
ck('UI 回滚后线上版本恢复基础模型',summary.summary.active_version==='V1.0-基础模型');
ck('回滚有回执且留在历史页签',await p.eval(`window.__receipts.some(t=>/回滚/.test(t))&&location.hash==='#tab=history'`));
ck('发布回滚无 JS 异常',!p.logs.some(x=>x.startsWith('[EXCEPTION]')));
await p.goto(base+'/model-center#tab=data');await p.settle(1800);
const beforeEvents=(await(await fetch(base+'/api/fault-events')).json()).events.length;
writeFileSync('/tmp/pex/ui-events.csv','设备编号,失效时间,故障类型,严重程度,处理措施\nPU-001,2026-11-19 10:00:00,轴承损伤,严重,更换轴承\n');
const {root}=await cdp.send('DOM.getDocument',{},p.sessionId);
const {nodeId}=await cdp.send('DOM.querySelector',{nodeId:root.nodeId,selector:'#evFile'},p.sessionId);
await cdp.send('DOM.setFileInputFiles',{nodeId,files:['/tmp/pex/ui-events.csv']},p.sessionId);await p.settle(300);
ck('事件文件预检按钮可点击',await click('#evPre'));
ck('预检显示可写入且未落库',await p.eval(`document.getElementById('evPreview').textContent.includes('可写入 1 条')`) && (await(await fetch(base+'/api/fault-events')).json()).events.length===beforeEvents);
ck('确认导入按钮可点击',await click('#evApply'));
ck('确认后显示回执、事件落库且页签不跳走',await p.eval(`document.getElementById('evPreview').textContent.includes('已写入 1 条')&&location.hash==='#tab=data'`) && (await(await fetch(base+'/api/fault-events')).json()).events.length===beforeEvents+1);
await p.close();cdp.close();chrome.reap();process.exit(fail?1:0);
